def heading(text, style, level=0):
    key = 'h_%s' % hashlib.md5(text.encode()).hexdigest()[:8]
    p = Paragraph('<a name="%s"/><b>%s</b>' % (key, text), style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p


def section(story_list, num, title):
    story_list.append(CondPageBreak(H1_ORPHAN))
    story_list.append(heading('%d. %s' % (num, title), h1, level=0))


def para(text):
    return Paragraph(text, body)


def bullets(items):
    return [Paragraph(it, bullet, bulletText='•') for it in items]


def make_table(headers, rows, ratios, align_center_cols=()):
    col_w = [r * AVAIL_W for r in ratios]
    assert sum(col_w) <= AVAIL_W + 0.5
    data = [[Paragraph('<b>%s</b>' % c, th) for c in headers]]
    for row in rows:
        cells = []
        for i, c in enumerate(row):
            st = td_c if i in align_center_cols else td
            cells.append(Paragraph(c, st))
        data.append(cells)
    t = Table(data, colWidths=col_w, hAlign='CENTER', repeatRows=1)
    style = [
        ('BACKGROUND', (0, 0), (-1, 0), TABLE_HEADER_COLOR),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('GRID', (0, 0), (-1, -1), 0.5, BORDER),
        ('LEFTPADDING', (0, 0), (-1, -1), 7),
        ('RIGHTPADDING', (0, 0), (-1, -1), 7),
        ('TOPPADDING', (0, 0), (-1, -1), 5.5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5.5),
    ]
    for r in range(1, len(data)):
        style.append(('BACKGROUND', (0, r), (-1, r),
                      TABLE_ROW_ODD if r % 2 == 0 else TABLE_ROW_EVEN))
    t.setStyle(TableStyle(style))
    return t


def callout_row(stats):
    """Linha de 3 stat-boxes (CalloutBox pattern)."""
    boxes = []
    w = (AVAIL_W - 24) / 3.0
    for value, label in stats:
        inner = Table([[Paragraph('<b>%s</b>' % value, stat_big)],
                       [Paragraph(label, stat_lbl)]], colWidths=[w])
        inner.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, -1), SECTION_BG),
            ('BOX', (0, 0), (-1, -1), 1, ACCENT),
            ('TOPPADDING', (0, 0), (-1, 0), 9),
            ('BOTTOMPADDING', (0, 1), (-1, 1), 9),
            ('TOPPADDING', (0, 1), (-1, 1), 2),
            ('BOTTOMPADDING', (0, 0), (-1, 0), 2),
        ]))
        boxes.append(inner)
    outer = Table([boxes], colWidths=[w + 12] * 3, hAlign='CENTER')
    outer.setStyle(TableStyle([
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
    ]))
    return outer


